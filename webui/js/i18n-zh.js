    var ATTRS = ["placeholder", "title", "aria-label", "data-original-title", "alt", "data-loading-text"];
    var SKIP = { SCRIPT: 1, STYLE: 1, CODE: 1, PRE: 1, TEXTAREA: 1, NOSCRIPT: 1 };

    function lookup(s) {
        if (!s) return null;
        var t = s.replace(/\s+/g, " ").trim();
        if (!t || !/[A-Za-z]/.test(t)) return null;
        if (D.hasOwnProperty(t)) return D[t];
        if (PLACEHOLDERS.hasOwnProperty(t)) return PLACEHOLDERS[t];
        if (PLACEHOLDERS.hasOwnProperty(t.toLowerCase())) return PLACEHOLDERS[t.toLowerCase()];
        for (var i = 0; i < RULES.length; i++) {
            if (RULES[i][0].test(t)) return t.replace(RULES[i][0], RULES[i][1]);
        }
        return null;
    }

    function translateText(s) {
        if (typeof s !== "string") return s;
        var t = lookup(s);
        return t === null ? s : t;
    }

    function fixTextNode(node) {
        var p = node.parentElement;
        if (!p || SKIP[p.tagName]) return;
        var old = node.nodeValue;
        if (!old || /[\u4e00-\u9fff]/.test(old)) return;
        var t = lookup(old);
        if (t === null) return;
        var m1 = old.match(/^\s*/)[0];
        var m2 = old.match(/\s*$/)[0];
        var next = m1 + t + m2;
        if (next !== old) node.nodeValue = next;
    }

    function fixAttributes(el) {
        for (var i = 0; i < ATTRS.length; i++) {
            var a = ATTRS[i];
            var v = el.getAttribute(a);
            if (!v || /[\u4e00-\u9fff]/.test(v)) continue;
            var t = lookup(v);
            if (t !== null && t !== v) el.setAttribute(a, t);
        }
    }

    function walk(root) {
        if (!root) return;
        if (root.nodeType === 3) { fixTextNode(root); return; }
        if (root.nodeType !== 1 || SKIP[root.tagName]) return;
        fixAttributes(root);
        for (var n = root.firstChild; n; n = n.nextSibling) walk(n);
    }

    function patchLabels(labels) {
        if (!labels || typeof labels.generateLabels !== "function" || labels.__zhPatched) return;
        var original = labels.generateLabels;
        labels.generateLabels = function (chart) {
            var items = original.call(this, chart);
            for (var i = 0; i < items.length; i++) {
                var t = lookup(items[i].text);
                if (t !== null) items[i].text = t;
            }
            return items;
        };
        labels.__zhPatched = true;
    }

    function translateChartInstance(chart) {
        if (!chart) return;

        if (chart.data && chart.data.labels) {
            for (var i = 0; i < chart.data.labels.length; i++) {
                var lt = lookup(chart.data.labels[i]);
                if (lt !== null) chart.data.labels[i] = lt;
            }
        }

        if (chart.data && chart.data.datasets) {
            for (var j = 0; j < chart.data.datasets.length; j++) {
                var ds = chart.data.datasets[j];
                if (ds && typeof ds.label === "string") {
                    var dt = lookup(ds.label);
                    if (dt !== null) ds.label = dt;
                }
            }
        }

        if (chart.options && chart.options.legend && chart.options.legend.labels) {
            patchLabels(chart.options.legend.labels);
        }

        chart.__zhPatched = true;
        if (typeof chart.update === "function") chart.update(0);
    }

    function patchUpdateChart() {
        if (typeof window.updateChart !== "function" || window.updateChart.__zhPatched) return;

        var original = window.updateChart;
        window.updateChart = function (chart, data) {
            original.call(this, chart, data);
            translateChartInstance(chart);
        };
        window.updateChart.__zhPatched = true;
    }

    function patchChartLegend() {
        var c = window.Chart;
        if (!c || !c.defaults) return;

        if (c.defaults.global && c.defaults.global.legend && c.defaults.global.legend.labels) {
            patchLabels(c.defaults.global.legend.labels);
        }
        if (c.defaults.plugins && c.defaults.plugins.legend && c.defaults.plugins.legend.labels) {
            patchLabels(c.defaults.plugins.legend.labels);
        }

        var instances = c.instances || (c.registry && c.registry.instances);
        if (instances) {
            for (var key in instances) {
                if (Object.prototype.hasOwnProperty.call(instances, key)) {
                    translateChartInstance(instances[key]);
                }
            }
        }
    }

