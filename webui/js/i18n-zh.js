    function patchDialogs() {
        if (typeof window.showAlert === "function" && !window.showAlert.__zhPatched) {
            var originalShowAlert = window.showAlert;
            window.showAlert = function (type, title, message, objAlertPlaceholder) {
                return originalShowAlert(type, translateText(title), translateText(message), objAlertPlaceholder);
            };
            window.showAlert.__zhPatched = true;
        }

        if (typeof window.confirm === "function" && !window.confirm.__zhPatched) {
            var originalConfirm = window.confirm;
            window.confirm = function (message) {
                return originalConfirm.call(window, translateText(message));
            };
            window.confirm.__zhPatched = true;
        }

        if (typeof window.alert === "function" && !window.alert.__zhPatched) {
            var originalAlert = window.alert;
            window.alert = function (message) {
                return originalAlert.call(window, translateText(message));
            };
            window.alert.__zhPatched = true;
        }
    }

